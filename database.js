require('dotenv').config();

const { Pool, types } = require('pg');

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required. Configure a PostgreSQL connection string in .env or Render.');
}

types.setTypeParser(20, Number);
types.setTypeParser(1700, Number);

const poolMax = Number.parseInt(process.env.PG_POOL_MAX || '10', 10);
if (!Number.isInteger(poolMax) || poolMax < 1) {
  throw new Error('PG_POOL_MAX must be a positive integer.');
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  max: poolMax,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000
});

pool.on('error', (error) => {
  console.error('Unexpected PostgreSQL pool error:', error);
});

async function query(sql, params = [], client = pool) {
  return client.query(sql, params);
}

async function get(sql, params = [], client = pool) {
  const result = await query(sql, params, client);
  return result.rows[0];
}

async function all(sql, params = [], client = pool) {
  const result = await query(sql, params, client);
  return result.rows;
}

async function run(sql, params = [], client = pool) {
  const result = await query(sql, params, client);
  return {
    id: result.rows[0]?.id,
    changes: result.rowCount
  };
}

async function withTransaction(operation) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await operation(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    try {
      await client.query('ROLLBACK');
    } catch (rollbackError) {
      console.error('Could not roll back PostgreSQL transaction:', rollbackError);
    }
    throw error;
  } finally {
    client.release();
  }
}

async function resetIdentity(client, table) {
  await client.query(
    `SELECT setval(
       pg_get_serial_sequence($1, 'id'),
       COALESCE((SELECT MAX(id) FROM ${table}), 1),
       EXISTS (SELECT 1 FROM ${table})
     )`,
    [`public.${table}`]
  );
}

async function initializeDatabase({ seed = true } = {}) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query(`CREATE TABLE IF NOT EXISTS products (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      brand TEXT NOT NULL,
      model TEXT NOT NULL,
      tyre_size TEXT NOT NULL,
      rim_size TEXT NOT NULL,
      vehicle_type TEXT NOT NULL,
      price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
      discount NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (discount >= 0 AND discount <= 100),
      stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
      image_url TEXT NOT NULL DEFAULT '',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);
    await client.query(`CREATE TABLE IF NOT EXISTS orders (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_name TEXT NOT NULL,
      phone TEXT NOT NULL,
      email TEXT NOT NULL,
      address TEXT NOT NULL,
      landmark TEXT NOT NULL DEFAULT '',
      pincode TEXT NOT NULL,
      city TEXT NOT NULL,
      state TEXT NOT NULL,
      vehicle_details TEXT NOT NULL DEFAULT '',
      product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
      brand TEXT NOT NULL,
      model TEXT NOT NULL,
      tyre_size TEXT NOT NULL,
      quantity INTEGER NOT NULL CHECK (quantity > 0),
      unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
      total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
      payment_method TEXT NOT NULL CHECK (payment_method IN ('cod', 'upi', 'online')),
      payment_status TEXT NOT NULL DEFAULT 'Pending',
      status TEXT NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled')),
      order_code TEXT,
      subtotal_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      gst_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      delivery_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      approval_status TEXT NOT NULL DEFAULT 'Approved & Dispatched',
      approved_at TIMESTAMPTZ,
      invoice_token_hash TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);
    await client.query(`ALTER TABLE orders
      ADD COLUMN IF NOT EXISTS order_code TEXT,
      ADD COLUMN IF NOT EXISTS subtotal_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      ADD COLUMN IF NOT EXISTS gst_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      ADD COLUMN IF NOT EXISTS delivery_amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
      ADD COLUMN IF NOT EXISTS approval_status TEXT NOT NULL DEFAULT 'Approved & Dispatched',
      ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ,
      ADD COLUMN IF NOT EXISTS invoice_token_hash TEXT`);
    await client.query(`CREATE TABLE IF NOT EXISTS order_items (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
      product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
      brand TEXT NOT NULL,
      model TEXT NOT NULL,
      tyre_size TEXT NOT NULL,
      quantity INTEGER NOT NULL CHECK (quantity > 0),
      unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
      subtotal_amount NUMERIC(12, 2) NOT NULL CHECK (subtotal_amount >= 0),
      gst_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (gst_amount >= 0)
    )`);
    await client.query(`ALTER TABLE order_items
      ADD COLUMN IF NOT EXISTS gst_amount NUMERIC(12, 2) NOT NULL DEFAULT 0`);
    await client.query(`CREATE TABLE IF NOT EXISTS app_settings (
      setting_key TEXT PRIMARY KEY,
      setting_value TEXT NOT NULL DEFAULT '',
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);

    await client.query('CREATE UNIQUE INDEX IF NOT EXISTS products_brand_model_size_idx ON products(brand, model, tyre_size)');
    await client.query('CREATE UNIQUE INDEX IF NOT EXISTS orders_order_code_idx ON orders(order_code)');
    await client.query('CREATE INDEX IF NOT EXISTS orders_created_at_idx ON orders(created_at DESC)');
    await client.query('CREATE UNIQUE INDEX IF NOT EXISTS order_items_order_product_idx ON order_items(order_id, product_id)');

    await client.query(
      `INSERT INTO order_items
       (order_id, product_id, brand, model, tyre_size, quantity, unit_price, subtotal_amount, gst_amount)
       SELECT orders.id, orders.product_id, orders.brand, orders.model, orders.tyre_size,
              orders.quantity, orders.unit_price, orders.subtotal_amount, orders.gst_amount
       FROM orders
       WHERE NOT EXISTS (SELECT 1 FROM order_items WHERE order_items.order_id = orders.id)
       ON CONFLICT DO NOTHING`
    );

    if (seed) {
      await seedInitialData(client);
      for (const table of ['products', 'orders', 'order_items']) {
        await resetIdentity(client, table);
      }
    }

    await client.query('COMMIT');
  } catch (error) {
    try {
      await client.query('ROLLBACK');
    } catch (rollbackError) {
      console.error('Could not roll back database initialization:', rollbackError);
    }
    throw error;
  } finally {
    client.release();
  }
}

